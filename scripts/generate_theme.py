#!/usr/bin/env python3
"""Generate Practices/Theme/Tokens.swift from design/tokens.json.

Run from the repo root:  python3 scripts/generate_theme.py
The generated file is checked in; regenerate it whenever tokens.json changes.
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
TOKENS = ROOT / "design" / "tokens.json"
OUT = ROOT / "Practices" / "Theme" / "Tokens.swift"


def hex_literal(value: str) -> str:
    return "0x" + value.lstrip("#").upper()


def swift_name(key: str) -> str:
    return key[0].lower() + key[1:]


def num(value) -> str:
    text = repr(float(value))
    return text[:-2] if text.endswith(".0") else text


def parse_blob(radius: str) -> list:
    """'58% 42% 54% 46% / 47% 55% 45% 53%' -> 8 fractions (horizontal then vertical)."""
    h, v = radius.split("/")
    values = [float(p.strip().rstrip("%")) / 100 for p in h.split() + v.split()]
    assert len(values) == 8, radius
    return values


def radii(values: list) -> str:
    return "CornerRadii(" + ", ".join(num(v) for v in values) + ")"


def main() -> None:
    t = json.loads(TOKENS.read_text())
    c = t["color"]
    lines = [
        "// Generated by scripts/generate_theme.py from design/tokens.json. Do not edit by hand.",
        "import CoreGraphics",
        "",
        "enum Tokens {",
        "    enum Palette {",
    ]
    for key, value in c.items():
        if isinstance(value, str):
            lines.append(f"        static let {swift_name(key)} = RGB({hex_literal(value)})")
        elif isinstance(value, (int, float)):
            lines.append(f"        static let {swift_name(key)}: Double = {num(value)}")
    lines.append("    }")
    lines.append("")
    lines.append("    /// Keyed by the mood's asset name (happy, calm, ..., badsleep, ...).")
    lines.append("    static let moodFaces: [String: RGB] = [")
    for key, value in c["moodFaces"].items():
        lines.append(f'        "{key}": RGB({hex_literal(value)}),')
    lines.append("    ]")
    lines.append("")

    ty = t["typography"]
    lines.append("    enum TypeScale {")
    lines.append(f'        static let family = "{ty["family"]}"')
    for key, s in ty["styles"].items():
        lines.append(
            f"        static let {swift_name(key)} = TextStyleToken(size: {num(s['size'])}, "
            f"lineHeight: {num(s['lineHeight'])}, weight: {int(s['weight'])}, tracking: {num(s.get('tracking', 0))})"
        )
    lines.append("    }")
    lines.append("")

    sp = t["spacing"]
    lines.append("    enum Spacing {")
    for key, value in sp.items():
        lines.append(f"        static let {swift_name(key)}: CGFloat = {num(value)}")
    lines.append("    }")
    lines.append("")

    sh = t["shape"]
    org = sh["organic"]
    wave = org["waveLine"]
    mf = sh["moodFace"]
    lines += [
        "    enum Shape {",
        f"        static let fabSize: CGFloat = {num(sh['fab']['size'])}",
        f"        static let fabTrailingInset: CGFloat = {num(sh['fab']['inset']['trailing'])}",
        f"        static let fabAboveTabBar: CGFloat = {num(sh['fab']['inset']['aboveTabBar'])}",
        f"        static let stepperButtonSize: CGFloat = {num(sh['stepperButton']['size'])}",
        f"        static let hairline: CGFloat = {num(sh['hairline'])}",
        f"        static let circleStroke: CGFloat = {num(sh['circleStroke'])}",
        "        /// Fractions of width (first four) and height (last four): TL, TR, BR, BL.",
        f"        static let blobRadius = {radii(parse_blob(org['blobRadius']))}",
        "        static let blobMorph: [CornerRadii] = [",
    ]
    for r in org["blobMorph"]:
        lines.append(f"            {radii(parse_blob(r))},")
    lines += [
        "        ]",
        f"        static let blobMorphSeconds: Double = {num(org['blobMorphSeconds'])}",
        "        /// Points: TL, TR, BR, BL horizontal, then TL, TR, BR, BL vertical.",
        f"        static let capsuleRadius = {radii(org['capsuleRadius'])}",
        f"        static let cardRadius = {radii(org['cardRadius'])}",
        f"        static let waveHalfPeriod: CGFloat = {num(wave['period'])}",
        f"        static let waveAmplitude: CGFloat = {num(wave['amplitude'])}",
        f"        static let waveStroke: CGFloat = {num(wave['stroke'])}",
        f"        static let waveColor = RGB({hex_literal(wave['color'])})",
        f"        static let checkFaceSize: CGFloat = {num(org['checkFaceSize'])}",
        "    }",
        "",
        "    enum MoodFace {",
    ]
    for key, value in mf["sizes"].items():
        lines.append(f"        static let {swift_name(key)}: CGFloat = {num(value)}")
    ring = mf["selectedRing"]
    lines += [
        f"        static let ringGap: CGFloat = {num(ring['gap'])}",
        f"        static let ringWidth: CGFloat = {num(ring['width'])}",
        f"        static let selectedScale: CGFloat = {num(mf['selectedScale'])}",
    ]
    for key, value in mf["dimmedOpacity"].items():
        lines.append(f"        static let {swift_name(key)}Opacity: Double = {num(value)}")
    lines += [
        f"        static let maxMoodsPerCheckIn = {int(mf['maxMoodsPerCheckIn'])}",
        "    }",
        "",
    ]

    m = t["motion"]
    lines += [
        "    enum Motion {",
        f"        static let buddyWobbleSeconds: Double = {num(m['buddyWobbleSeconds'])}",
        f"        static let buddyBobPoints: CGFloat = {num(m['buddyBobPoints'])}",
        f"        static let buddyBobSeconds: [Double] = [{', '.join(num(v) for v in m['buddyBobSeconds'])}]",
        f"        static let waveSeconds: Double = {num(m['waveSeconds'])}",
        f"        static let wavePeriod: CGFloat = {num(m['wavePeriod'])}",
        f"        static let waveAmplitude: CGFloat = {num(m['waveAmplitude'])}",
        f"        static let tapBounceSeconds: Double = {num(m['tapBounce']['duration'])}",
        "        static let tapBounceKeyframes: [CGSize] = [",
    ]
    for x, y in m["tapBounce"]["keyframes"]:
        lines.append(f"            CGSize(width: {num(x)}, height: {num(y)}),")
    conf = m["confetti"]
    lines += [
        "        ]",
        f"        static let confettiPieces = {int(conf['pieces'])}",
        f"        static let confettiDistance: [CGFloat] = [{', '.join(num(v) for v in conf['distance'])}]",
        f"        static let confettiSeconds: Double = {num(conf['seconds'])}",
        "    }",
        "",
    ]

    goals = t["defaults"]["goals"]
    lines += [
        "    enum Defaults {",
        f'        static let weekStartsOnMonday = {"true" if t["defaults"]["weekStartsOn"] == "Monday" else "false"}',
        f"        static let meditationMinutesPerDay = {int(goals['meditationMinutesPerDay'])}",
        f"        static let exerciseMinutesPerDay = {int(goals['exerciseMinutesPerDay'])}",
        "    }",
        "}",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"Wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
